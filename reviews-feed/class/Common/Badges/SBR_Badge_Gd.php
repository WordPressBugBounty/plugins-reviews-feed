<?php

namespace SmashBalloon\Reviews\Common\Badges;

use SmashBalloon\Reviews\Common\DisplayElements;

/**
 * The badge email image, drawn with GD instead of Imagick.
 *
 * Why this exists: Imagick is not on most shared hosts, and GD cannot rasterise
 * SVG at all — so `wp_image_editor_supports()` says yes on a host that can never
 * draw this badge. Rather than a second layout, this REPLAYS the SVG that
 * SBR_Badge_Image::build_svg() already produced. Every coordinate in that SVG
 * comes from text_width()'s metric table, not from a font, so the geometry is
 * identical whichever rasteriser consumes it — which is why the two outputs
 * measure the same size to the pixel.
 *
 * Measured against Imagick on four badges (card, chip, medal, two-source):
 * mean absolute per-pixel difference 4.15-6.04 of 255, and what differs is edge
 * antialiasing and glyph shape. See .claude/qa/gd-vs-imagick/ for the comparison
 * that decided the fallback order.
 *
 * Three things GD needs that Imagick did not:
 *
 * 1. A font FILE. imagettftext takes a path, and the hosts without Imagick also
 *    tend to lack Arial — the box we QA on carries only DejaVu, which is wider.
 *    Nothing is bundled; a font is located, and every string is then scaled so
 *    the run fits the width the layout reserved. A slightly smaller line beats
 *    one that overflows its box.
 * 2. The stars as geometry. The star path is all straight lines, so it is a
 *    polygon and imagefilledpolygon draws it exactly.
 * 3. The provider marks as rasters, because they are real vector art. Derived
 *    PNGs live in assets/badge-marks, generated by build/generate-badge-marks.php
 *    from the same SVGs the page uses.
 *
 * @package SB_Reviews
 */
class SBR_Badge_Gd
{
	/**
	 * Supersample factor. GD's polygon and arc fills are not antialiased, so a
	 * rounded corner or a star point drawn at final size stair-steps against
	 * Imagick's. Drawn large and reduced, which is antialiasing by resampling.
	 */
	const SUPERSAMPLE = 4;

	/**
	 * Where the bundled faces live, relative to the plugin directory.
	 *
	 * A constant rather than an inline literal so the path appears once — the
	 * candidate list, the bold variant and the tests all read it.
	 */
	const BUNDLED_FONT_REL = 'assets/fonts/';

	/**
	 * Ceiling on the SUPERSAMPLED canvas, in pixels.
	 *
	 * 40M pixels is about 160 MB of truecolour, and still allows a badge of
	 * roughly 1580x1580 logical — far past anything build_svg() emits.
	 */
	const MAX_CANVAS_PIXELS = 40000000;

	/**
	 * Resolved font paths, keyed 'regular' / 'bold'.
	 *
	 * @var array<string, string>
	 */
	private static $font_cache = array();

	/**
	 * imagettftext sizes in POINTS; SVG font-size is user units. At 96dpi that
	 * is 4:3, and the first version of this renderer drew every string 33% too
	 * big by passing the SVG number straight through.
	 */
	const PT_PER_PX = 0.75;

	/**
	 * Font files to try, in order of how close their metrics are to the Arial
	 * advances text_width() is built on. Liberation and Arimo are
	 * metric-compatible; DejaVu is wider and is the last resort, which is why
	 * the run is scaled to fit rather than trusted.
	 *
	 * @var string[]
	 */
	const FONT_CANDIDATES = array(
		'/usr/share/fonts/truetype/liberation/LiberationSans-Regular.ttf',
		'/usr/share/fonts/truetype/liberation2/LiberationSans-Regular.ttf',
		'/usr/share/fonts/truetype/croscore/Arimo-Regular.ttf',
		'/usr/share/fonts/truetype/msttcorefonts/Arial.ttf',
		'/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf',
		'/usr/share/fonts/dejavu/DejaVuSans.ttf',
		'/Library/Fonts/Arial.ttf',
		'/System/Library/Fonts/Supplemental/Arial.ttf',
	);

	/**
	 * Whether this host can draw the badge with GD.
	 *
	 * Three separate capabilities, and a host can have the first without the
	 * others: the extension, FreeType (imagettftext is a separate build option),
	 * and a font file to point it at.
	 *
	 * @return bool
	 */
	public static function available()
	{
		return extension_loaded('gd')
			&& function_exists('imagettftext')
			&& function_exists('imagefilledpolygon')
			&& self::font(false) !== '';
	}

	/**
	 * A readable TTF, or '' when the host has none.
	 *
	 * Filterable because a host can have a perfectly good font somewhere this
	 * list does not guess. Returning a path that is not readable would fail at
	 * the draw call with nothing said, so the filtered value is checked too.
	 *
	 * @param bool $bold Whether the bold face is wanted.
	 *
	 * @return string
	 */
	public static function font($bold = false)
	{
		// A class property, not a function static. Behaviour is identical, but a
		// function static cannot be reached from a test — so the guard asserting
		// that probing is SILENT was measuring a cache hit left by an earlier
		// test in the same process and could not fail. Reachable state is the
		// difference between a guard and a decoration.
		$cache = &self::$font_cache;

		$key = $bold ? 'bold' : 'regular';

		if (isset($cache[ $key ])) {
			return $cache[ $key ];
		}

		$found = '';

		foreach (self::font_candidates() as $candidate) {
			$path = $bold ? self::bold_variant($candidate) : $candidate;

			if (is_readable($path)) {
				$found = $path;
				break;
			}

			// A family with no bold face on disk still draws, just not bold.
			if ($bold && is_readable($candidate)) {
				$found = $candidate;
				break;
			}
		}

		/**
		 * Filters the font file the GD badge renderer draws with.
		 *
		 * @since 2.12.0
		 *
		 * @param string $found Absolute path, or '' when none was located.
		 */
		$found = (string) apply_filters('sbr_badge_gd_font', $found);

		$resolved = is_readable($found) ? $found : '';

		$cache[ $key ] = $resolved;

		// The local, not the slot just written — re-reading the offset is what the
		// analyser cannot prove, and it is the same value.
		return $resolved;
	}

	/**
	 * Every face to try, bundled one first.
	 *
	 * The bundled face leads because every entry in FONT_CANDIDATES is an
	 * absolute SYSTEM path, and on a host whose open_basedir is the webroot —
	 * standard shared hosting, which is the host class this rung exists for —
	 * all eight are unreadable AND each probe raises a PHP warning. Measured on
	 * a QA box: eight warnings per render, font() returned '', and the email
	 * badge answered 503 because the chain correctly refused to draw.
	 *
	 * Liberation Sans is the right face to ship rather than any free font:
	 * build_svg() lays the badge out from a hardcoded Helvetica advance-width
	 * table, and Liberation is metrically identical to Arial and Helvetica, so
	 * the text lands where the geometry planned. Shipping DejaVu instead moved
	 * the mean per-pixel difference against Imagick from ~3.2 to ~7.0.
	 *
	 * @return array<int, string>
	 */
	protected static function font_candidates()
	{
		$bundled = array();

		if (defined('SBR_PLUGIN_DIR')) {
			$bundled[] = SBR_PLUGIN_DIR . self::BUNDLED_FONT_REL . 'LiberationSans-Regular.ttf';
		}

		return array_merge($bundled, self::FONT_CANDIDATES);
	}

	/**
	 * The bold filename for a regular one, by the convention each family uses.
	 *
	 * @param string $regular Path to the regular face.
	 *
	 * @return string
	 */
	protected static function bold_variant($regular)
	{
		$map = array(
			'-Regular.ttf' => '-Bold.ttf',
			'Sans.ttf'     => 'Sans-Bold.ttf',
			'Arial.ttf'    => 'Arial Bold.ttf',
		);

		foreach ($map as $from => $to) {
			if (substr($regular, -strlen($from)) === $from) {
				return substr($regular, 0, -strlen($from)) . $to;
			}
		}

		return $regular;
	}

	/**
	 * Replay a badge SVG with GD and composite its rasters.
	 *
	 * @param string  $svg     Markup from SBR_Badge_Image::build_svg().
	 * @param array[] $rasters Entries of x, y, w, h, png.
	 *
	 * @return string PNG bytes, or '' when the SVG could not be replayed.
	 */
	public static function render($svg, array $rasters = array())
	{
		if (! self::available()) {
			return '';
		}

		if (! preg_match('/<svg[^>]*width="([\d.]+)"[^>]*height="([\d.]+)"/', $svg, $dim)) {
			return '';
		}

		$w = (int) round((float) $dim[1]);
		$h = (int) round((float) $dim[2]);

		if ($w < 1 || $h < 1 || $w > 4000 || $h > 4000) {
			return '';
		}

		$ss = self::SUPERSAMPLE;

		// The per-axis cap above bounds the LOGICAL size; what gets allocated is
		// the supersampled canvas, which is SUPERSAMPLE^2 times the pixels — so
		// 4000x4000 permitted here is 16000x16000 allocated, about a gigabyte of
		// truecolour, and GD allocates outside PHP's memory_limit. Measured
		// against real output the largest badge this layout produces is 446x216
		// (about 3.5 MB supersampled), and a 50,000-character footer does not
		// move it, so this budget is orders of magnitude above anything
		// reachable — it is here so the axis caps and the supersample factor
		// cannot drift into an allocation nobody checked.
		if ($w * $ss * $h * $ss > self::MAX_CANVAS_PIXELS) {
			return '';
		}

		$canvas = self::transparent($w * $ss, $h * $ss);

		if ($canvas === null) {
			return '';
		}

		$scale = self::text_scale();

		// Document order matters: later elements paint over earlier ones, which
		// is how the surface sits under the divider and the text over both.
		// `path` is in the list because the FOOTER BAND is one — see
		// SBR_Badge_Image::footer_band_svg(). Without it GD drew the attribution
		// text straight onto the surface with no strip behind it, on all three
		// styles, and the per-pixel comparison that signed off the GD rung could
		// not see it: the band is about 6/255 from the surface over a tenth of
		// the area. Attribution is forced below Pro Plus, so most badges.
		preg_match_all('/<(rect|text|circle|path)\b([^>]*)>([^<]*)/', $svg, $elements, PREG_SET_ORDER);

		foreach ($elements as $element) {
			list( , $tag, $attrs, $inner ) = $element;

			if ($tag === 'rect') {
				self::draw_rect($canvas, $attrs, $ss);
			} elseif ($tag === 'circle') {
				self::draw_circle($canvas, $attrs, $ss);
			} elseif ($tag === 'path') {
				self::draw_footer_band($canvas, $attrs, $ss);
			} else {
				self::draw_text($canvas, $attrs, $inner, $ss, $scale);
			}
		}

		$flat = self::transparent($w, $h);

		if ($flat === null) {
			imagedestroy($canvas);

			return '';
		}

		imagecopyresampled($flat, $canvas, 0, 0, 0, 0, $w, $h, $w * $ss, $h * $ss);
		imagedestroy($canvas);

		imagealphablending($flat, true);

		foreach ($rasters as $raster) {
			self::composite($flat, $raster);
		}

		ob_start();
		imagepng($flat);
		$png = (string) ob_get_clean();
		imagedestroy($flat);

		return $png;
	}

	/**
	 * A transparent truecolour canvas, or null when GD refuses the size.
	 *
	 * @param int $w Width.
	 * @param int $h Height.
	 *
	 * @return \GdImage|null
	 */
	protected static function transparent($w, $h)
	{
		$im = imagecreatetruecolor($w, $h);

		if (! $im) {
			return null;
		}

		imagealphablending($im, false);
		imagesavealpha($im, true);
		$clear = imagecolorallocatealpha($im, 0, 0, 0, 127);
		imagefill($im, 0, 0, false === $clear ? 0 : $clear);
		imagealphablending($im, true);

		return $im;
	}

	/**
	 * How much every string has to shrink for the located font to fit the boxes
	 * text_width() measured with Helvetica advances.
	 *
	 * One factor for the whole badge rather than per string, so the two lines of
	 * a card stay in proportion with each other. Never above 1: a narrower font
	 * is left alone rather than stretched.
	 *
	 * @return float
	 */
	protected static function text_scale()
	{
		// A reference run with digits, spacing and lowercase — the three things
		// the badge actually draws.
		$reference = 'Based on 4,775 reviews';
		$size      = 24;
		$expected  = 256.1; // text_width( $reference, 24 ), which is what the layout used.

		$box = imagettfbbox($size * self::PT_PER_PX, 0, self::font(false), $reference);

		if (! is_array($box) || ! isset($box[0], $box[2])) {
			return 1.0;
		}

		$actual = abs((float) $box[2] - (float) $box[0]);

		if ($actual <= 0) {
			return 1.0;
		}

		return min(1.0, $expected / $actual);
	}

	/**
	 * One attribute off an element's attribute string.
	 *
	 * @param string      $attrs   Raw attributes.
	 * @param string      $name    Attribute name.
	 * @param string|null $default Returned when absent.
	 *
	 * @return string|null
	 */
	protected static function attr(string $attrs, string $name, ?string $default = null): ?string
	{
		if (preg_match('/\b' . preg_quote($name, '/') . '="([^"]*)"/', $attrs, $m)) {
			return (string) $m[1];
		}

		return $default;
	}

	/**
	 * Allocate a colour from a hex string.
	 *
	 * @param \GdImage    $im  Canvas.
	 * @param string|null $hex Colour, with or without '#'. Null draws black.
	 *
	 * @return int
	 */
	protected static function colour($im, ?string $hex)
	{
		$hex = ltrim((string) $hex, '#');

		if (strlen($hex) === 3) {
			$hex = $hex[0] . $hex[0] . $hex[1] . $hex[1] . $hex[2] . $hex[2];
		}

		if (strlen($hex) < 6) {
			$black = imagecolorallocate($im, 0, 0, 0);

			return false === $black ? 0 : $black;
		}

		$allocated = imagecolorallocate(
			$im,
			(int) hexdec(substr($hex, 0, 2)),
			(int) hexdec(substr($hex, 2, 2)),
			(int) hexdec(substr($hex, 4, 2))
		);

		// Allocation fails only on a palette image that is already full, which
		// cannot happen on the truecolour canvases here — but returning false
		// where an int is declared would be a lie about the contract.
		return false === $allocated ? 0 : $allocated;
	}

	/**
	 * A <rect>, with or without rounded corners and a stroke.
	 *
	 * @param \GdImage            $im    Canvas.
	 * @param string            $attrs Element attributes.
	 * @param int               $ss    Supersample factor.
	 *
	 * @return void
	 */
	protected static function draw_rect($im, $attrs, $ss)
	{
		$x  = (float) self::attr($attrs, 'x', '0') * $ss;
		$y  = (float) self::attr($attrs, 'y', '0') * $ss;
		$w  = (float) self::attr($attrs, 'width', '0') * $ss;
		$h  = (float) self::attr($attrs, 'height', '0') * $ss;
		$r  = (float) self::attr($attrs, 'rx', '0') * $ss;
		$sw = (float) self::attr($attrs, 'stroke-width', '0') * $ss;

		$fill   = self::attr($attrs, 'fill');
		$stroke = self::attr($attrs, 'stroke');
		$has_stroke = $stroke !== null && $stroke !== 'none' && $sw > 0;

		if ($w < 1 || $h < 1) {
			return;
		}

		// An SVG stroke straddles the edge, so the stroked shape is half a width
		// larger all round and the fill sits half a width inside it.
		if ($has_stroke) {
			self::rounded_rect($im, $x - $sw / 2, $y - $sw / 2, $w + $sw, $h + $sw, $r + $sw / 2, self::colour($im, $stroke));
		}

		if ($fill !== null && $fill !== 'none') {
			$inset = $has_stroke ? $sw / 2 : 0;
			self::rounded_rect($im, $x + $inset, $y + $inset, $w - $inset * 2, $h - $inset * 2, max(0, $r - $inset), self::colour($im, $fill));
		}
	}

	/**
	 * A <circle>, which the medal layout draws behind a single mark.
	 *
	 * @param \GdImage            $im    Canvas.
	 * @param string            $attrs Element attributes.
	 * @param int               $ss    Supersample factor.
	 *
	 * @return void
	 */
	protected static function draw_circle($im, $attrs, $ss)
	{
		$cx = (float) self::attr($attrs, 'cx', '0') * $ss;
		$cy = (float) self::attr($attrs, 'cy', '0') * $ss;
		$r  = (float) self::attr($attrs, 'r', '0') * $ss;
		$sw = (float) self::attr($attrs, 'stroke-width', '0') * $ss;

		$fill   = self::attr($attrs, 'fill');
		$stroke = self::attr($attrs, 'stroke');
		$has_stroke = $stroke !== null && $stroke !== 'none' && $sw > 0;

		if ($r < 1) {
			return;
		}

		if ($has_stroke) {
			$d = (int) round(( $r + $sw / 2 ) * 2);
			imagefilledellipse($im, (int) round($cx), (int) round($cy), $d, $d, self::colour($im, $stroke));
		}

		if ($fill !== null && $fill !== 'none') {
			$inset = $has_stroke ? $sw / 2 : 0;
			$d     = (int) round(( $r - $inset ) * 2);
			imagefilledellipse($im, (int) round($cx), (int) round($cy), $d, $d, self::colour($im, $fill));
		}
	}

	/**
	 * A <text>, at the baseline the SVG gives.
	 *
	 * @param \GdImage            $im    Canvas.
	 * @param string            $attrs Element attributes.
	 * @param string            $inner Text content, still entity-encoded.
	 * @param int               $ss    Supersample factor.
	 * @param float             $scale Global run-fitting factor.
	 *
	 * @return void
	 */
	protected static function draw_text($im, $attrs, $inner, $ss, $scale)
	{
		$text = html_entity_decode($inner, ENT_QUOTES | ENT_HTML5, 'UTF-8');

		if (trim($text) === '') {
			return;
		}

		$x    = (float) self::attr($attrs, 'x', '0') * $ss;
		$y    = (float) self::attr($attrs, 'y', '0') * $ss;
		$bold = self::attr($attrs, 'font-weight') === '700';
		$font = self::font($bold);

		if ($font === '') {
			return;
		}

		// GD's y is the baseline, the same as SVG's, so no conversion.
		$size = (float) self::attr($attrs, 'font-size', '16') * $ss * self::PT_PER_PX * $scale;

		if (self::attr($attrs, 'text-anchor') === 'middle') {
			$box = imagettfbbox($size, 0, $font, $text);

			if (is_array($box) && isset($box[0], $box[2])) {
				$x -= abs((float) $box[2] - (float) $box[0]) / 2;
			}
		}

		imagettftext($im, $size, 0, (int) round($x), (int) round($y), self::colour($im, self::attr($attrs, 'fill', '#000000')), $font, $text);
	}

	/**
	 * The footer band, the one `path` this replay understands.
	 *
	 * Deliberately narrow: it matches the shape footer_band_svg() emits and
	 * ignores every other path rather than growing into a path interpreter. The
	 * shape is a rectangle whose BOTTOM two corners are rounded, so it is drawn
	 * as a rounded rect with the top corners squared back — rounded_rect()
	 * rounds all four.
	 *
	 * @param \GdImage $im    Canvas.
	 * @param string   $attrs The element's attributes.
	 * @param int      $ss    Supersample factor.
	 *
	 * @return void
	 */
	protected static function draw_footer_band($im, $attrs, $ss)
	{
		$d = self::attr($attrs, 'd');

		if ($d === null) {
			return;
		}

		// M2 <band_y> H<right> V<bottom-r> a<r> ... — anything else is not ours.
		if (! preg_match('/^M2\s+([\d.]+)\s+H([\d.]+)\s+V([\d.]+)\s+a([\d.]+)/', trim($d), $m)) {
			return;
		}

		$col = self::colour($im, self::attr($attrs, 'fill'));

		if ($col === false) {
			return;
		}

		$left   = 2 * $ss;
		$top    = (float) $m[1] * $ss;
		$right  = (float) $m[2] * $ss;
		$radius = (float) $m[4] * $ss;
		$bottom = ( (float) $m[3] * $ss ) + $radius;

		$w = $right - $left;
		$h = $bottom - $top;

		if ($w <= 0 || $h <= 0) {
			return;
		}

		self::rounded_rect($im, $left, $top, $w, $h, $radius, $col);

		// Square the top back: the band's top edge butts against the surface.
		imagefilledrectangle(
			$im,
			(int) round($left),
			(int) round($top),
			(int) round($right - 1),
			(int) round($top + $radius),
			$col
		);
	}

	/**
	 * A filled rounded rectangle, which GD has no primitive for.
	 *
	 * @param \GdImage            $im  Canvas.
	 * @param float             $x   Left.
	 * @param float             $y   Top.
	 * @param float             $w   Width.
	 * @param float             $h   Height.
	 * @param float             $r   Corner radius.
	 * @param int               $col Allocated colour.
	 *
	 * @return void
	 */
	protected static function rounded_rect($im, $x, $y, $w, $h, $r, $col)
	{
		$x = (int) round($x);
		$y = (int) round($y);
		$w = (int) round($w);
		$h = (int) round($h);
		$r = (int) round($r);
		$r = max(0, min($r, (int) floor(min($w, $h) / 2)));

		if ($r === 0) {
			imagefilledrectangle($im, $x, $y, $x + $w - 1, $y + $h - 1, $col);

			return;
		}

		imagefilledrectangle($im, $x + $r, $y, $x + $w - $r - 1, $y + $h - 1, $col);
		imagefilledrectangle($im, $x, $y + $r, $x + $w - 1, $y + $h - $r - 1, $col);

		$d = $r * 2;
		imagefilledarc($im, $x + $r, $y + $r, $d, $d, 180, 270, $col, IMG_ARC_PIE);
		imagefilledarc($im, $x + $w - $r - 1, $y + $r, $d, $d, 270, 360, $col, IMG_ARC_PIE);
		imagefilledarc($im, $x + $r, $y + $h - $r - 1, $d, $d, 90, 180, $col, IMG_ARC_PIE);
		imagefilledarc($im, $x + $w - $r - 1, $y + $h - $r - 1, $d, $d, 0, 90, $col, IMG_ARC_PIE);
	}

	/**
	 * Draw one collected raster onto the badge.
	 *
	 * A raster that will not decode is SKIPPED rather than allowed to abort the
	 * badge — the same rule composite_rasters() follows for Imagick, so one
	 * unreadable provider mark costs that mark and not the whole image.
	 *
	 * @param \GdImage            $im     Canvas.
	 * @param array             $raster Entry of x, y, w, h, png.
	 *
	 * @return void
	 */
	protected static function composite($im, array $raster)
	{
		if (empty($raster['png'])) {
			return;
		}

		// phpcs:ignore WordPress.PHP.NoSilencedErrors.Discouraged -- bytes come from our own
		// rasteriser and a corrupt raster is skipped below; the warning would print into the page.
		$src = @imagecreatefromstring((string) $raster['png']);

		if (! $src) {
			return;
		}

		if (! isset($raster['x'], $raster['y'], $raster['w'], $raster['h'])) {
			imagedestroy($src);

			return;
		}

		imagecopyresampled(
			$im,
			$src,
			(int) round((float) $raster['x']),
			(int) round((float) $raster['y']),
			0,
			0,
			(int) round((float) $raster['w']),
			(int) round((float) $raster['h']),
			imagesx($src),
			imagesy($src)
		);

		imagedestroy($src);
	}

	/**
	 * The five-star row, as PNG bytes.
	 *
	 * The star path in SBR_Badge_Image::star_png() is every-command-a-line, so
	 * it is a polygon and GD draws it exactly. Parsed rather than hardcoded so
	 * the two renderers cannot drift apart when the glyph changes.
	 *
	 * @param float  $rating  Rating out of five.
	 * @param array  $palette Resolved palette, with `star` and `starBase`.
	 * @param float  $size    Star size in CSS pixels.
	 * @param float  $gap     Gap between stars.
	 * @param float  $scale   Device scale.
	 *
	 * @return string PNG bytes, or '' when the row could not be drawn.
	 */
	public static function star_row($rating, array $palette, $size, $gap, $scale)
	{
		if (! self::available()) {
			return '';
		}

		$points = self::star_points();

		if (! $points) {
			return '';
		}

		$ss = self::SUPERSAMPLE;
		$w  = (int) round((( $size * 5 ) + ( $gap * 4 )) * $scale);
		$h  = (int) round($size * $scale);

		$canvas = self::transparent($w * $ss, $h * $ss);

		if ($canvas === null) {
			return '';
		}

		// Floors to a half for the same reason the template does: five glyphs
		// cannot draw 4.8.
		$display = floor(max(0, min(5, (float) $rating)) * 2) / 2;
		$star    = isset($palette['star']) ? $palette['star'] : '#f0b101';
		$base    = isset($palette['starBase']) ? $palette['starBase'] : '#e5e7eb';
		$px      = $size * $scale * $ss;

		for ($i = 0; $i < 5; $i++) {
			$left      = $i * ( $size + $gap ) * $scale * $ss;
			$remainder = $display - $i;

			if ($remainder >= 1) {
				self::star($canvas, $points, $left, 0, $px, self::colour($canvas, $star));
				continue;
			}

			self::star($canvas, $points, $left, 0, $px, self::colour($canvas, $base));

			if ($remainder === 0.5) {
				// LEFT half, which is the half the page fills. Clipped by drawing
				// the full glyph into a scratch canvas and copying half across —
				// GD has no clip region.
				$half = self::transparent((int) round($px), (int) round($px));

				if ($half !== null) {
					self::star($half, $points, 0, 0, $px, self::colour($half, $star));
					imagecopy($canvas, $half, (int) round($left), 0, 0, 0, (int) round($px / 2), (int) round($px));
					imagedestroy($half);
				}
			}
		}

		$flat = self::transparent($w, $h);

		if ($flat === null) {
			imagedestroy($canvas);

			return '';
		}

		imagecopyresampled($flat, $canvas, 0, 0, 0, 0, $w, $h, $w * $ss, $h * $ss);
		imagedestroy($canvas);

		ob_start();
		imagepng($flat);
		$png = (string) ob_get_clean();
		imagedestroy($flat);

		return $png;
	}

	/**
	 * One star glyph.
	 *
	 * @param \GdImage            $im     Canvas.
	 * @param float[]           $points Unit-space vertices, x,y interleaved.
	 * @param float             $x      Left offset.
	 * @param float             $y      Top offset.
	 * @param float             $px     Glyph size.
	 * @param int               $col    Allocated colour.
	 *
	 * @return void
	 */
	protected static function star($im, array $points, $x, $y, $px, $col)
	{
		$scaled = array();

		$total = count($points);

		for ($i = 0; $i + 1 < $total; $i += 2) {
			if (! isset($points[ $i ], $points[ $i + 1 ])) {
				break;
			}

			// The path's own viewBox is 0 0 20 20.
			$scaled[] = (int) round($x + ( $points[ $i ] / 20 ) * $px);
			$scaled[] = (int) round($y + ( $points[ $i + 1 ] / 20 ) * $px);
		}

		// The 3-argument form is PHP 8.0+, and this plugin declares 7.4
		// (readme.txt "Requires PHP: 7.4", composer.json ">=7.4"). On 7.4 the
		// point count is required, so the short call is an ArgumentCountError —
		// a fatal on any badge with stars, which is the default. available()
		// cannot catch it either: function_exists('imagefilledpolygon') is true
		// on 7.4, so the capability probe would fail open.
		if (PHP_VERSION_ID >= 80000) {
			imagefilledpolygon($im, $scaled, $col);
		} else {
			// Deprecated in 8.1, which is why it is not the branch taken there.
			imagefilledpolygon($im, $scaled, (int) ( count($scaled) / 2 ), $col);
		}
	}

	/**
	 * The star outline, as vertices in its own 20x20 space.
	 *
	 * Parses the same `d` attribute SBR_Badge_Image::star_png() hands Imagick.
	 * Absolute and relative commands both appear in it, and there are implicit
	 * repeats — reading it as all-absolute pulls 8 vertices out of a
	 * five-pointed star and draws a shape that is not a star at all.
	 *
	 * @return float[] x,y interleaved. Empty when the path could not be read.
	 */
	public static function star_points()
	{
		$d = SBR_Badge_Image::STAR_PATH;

		preg_match_all('/([MLmlZz])|(-?\d*\.?\d+)/', $d, $matches, PREG_SET_ORDER);

		$tokens = array();

		foreach ($matches as $match) {
			$tokens[] = isset($match[1]) && '' !== $match[1]
				? $match[1]
				: (float) ( isset($match[2]) ? $match[2] : 0 );
		}

		$points = array();
		$cmd    = 'L';
		$x      = 0.0;
		$y      = 0.0;
		$i      = 0;
		$count  = count($tokens);

		while ($i < $count) {
			if (! isset($tokens[ $i ])) {
				break;
			}

			if (is_string($tokens[ $i ])) {
				$cmd = $tokens[ $i ];
				$i++;
				continue;
			}

			if (! isset($tokens[ $i + 1 ]) || is_string($tokens[ $i + 1 ])) {
				break;
			}

			$a = (float) $tokens[ $i ];
			$b = (float) $tokens[ $i + 1 ];
			$i += 2;

			if ('M' === $cmd || 'L' === $cmd) {
				$x = $a;
				$y = $b;
			} else {
				$x += $a;
				$y += $b;
			}

			$points[] = $x;
			$points[] = $y;

			// A moveto's extra coordinate pairs are implicit linetos.
			if ('M' === $cmd) {
				$cmd = 'L';
			} elseif ('m' === $cmd) {
				$cmd = 'l';
			}
		}

		// A polygon needs three vertices; a star needs ten. Fewer means the path
		// was misread, and drawing it would be worse than drawing nothing.
		return count($points) >= 20 ? $points : array();
	}

	/**
	 * A provider mark, from the derived PNG set.
	 *
	 * @param string $provider Provider key.
	 * @param string $variant  'icon', 'mono' or 'lockup'.
	 * @param string $ink      Hex to tint a mono mark to, or '' to keep as-is.
	 * @param int    $w        Target width in CSS pixels.
	 * @param int    $h        Target height in CSS pixels.
	 *
	 * @return array{png: string, w: int, h: int}|null
	 */
	public static function mark($provider, $variant, $ink, $w, $h): ?array
	{
		$path = self::mark_path($provider, $variant);

		if ($path === '') {
			return null;
		}

		// phpcs:ignore WordPress.PHP.NoSilencedErrors.Discouraged -- a mark PNG that will not
		// decode is handled as a missing mark below; the warning would print into the page.
		$src = @imagecreatefrompng($path);

		if (! $src) {
			return null;
		}

		$sw = imagesx($src);
		$sh = imagesy($src);

		// No zero-dimension guard here on purpose, and it is worth writing down
		// because it looks like an omission. libpng refuses a 0-height IHDR, so
		// imagecreatefrompng() returns false and the `! $src` check above has
		// already caught it — measured against a hand-built 8x0 PNG. phpstan says
		// the same from the type side: imagesx()/imagesy() are int<1, max>, so a
		// `< 1` test is dead code it rejects at level 9.
		//
		// Height drives the scale, the same way `height: Npx; width: auto` does
		// on the page, so a wide lockup is not squashed into a square box.
		$target_h = (int) round($h * 2);
		$target_w = (int) round($sw * ( $target_h / $sh ));

		if ($target_w > $w * 2) {
			$target_w = (int) round($w * 2);
			$target_h = (int) round($sh * ( $target_w / $sw ));
		}

		$target_w = max(1, $target_w);
		$target_h = max(1, $target_h);
		$out      = self::transparent($target_w, $target_h);

		if ($out === null) {
			imagedestroy($src);

			return null;
		}

		imagecopyresampled($out, $src, 0, 0, 0, 0, $target_w, $target_h, $sw, $sh);
		imagedestroy($src);

		if ($ink !== '') {
			self::tint($out, $ink);
		}

		ob_start();
		imagepng($out);
		$png = (string) ob_get_clean();
		imagedestroy($out);

		if ($png === '') {
			return null;
		}

		return array(
			'png' => $png,
			'w'   => (int) round($target_w / 2),
			'h'   => (int) round($target_h / 2),
		);
	}

	/**
	 * The derived PNG for a mark, or '' when there is none.
	 *
	 * @param string $provider Provider key.
	 * @param string $variant  Asset variant.
	 *
	 * @return string
	 */
	public static function mark_path($provider, $variant)
	{
		$slug = DisplayElements::provider_asset_slug($provider);

		if (! is_string($slug) || $slug === '') {
			return '';
		}

		// Nothing here comes from a request, but a slug is still pinned to the
		// charset the generator writes rather than trusted into a path.
		if (! preg_match('/^[a-z0-9._-]+$/', $slug) || ! preg_match('/^[a-z]+$/', (string) $variant)) {
			return '';
		}

		$path = dirname(__DIR__, 3) . '/assets/badge-marks/' . $slug . '-' . $variant . '.png';

		return is_readable($path) ? $path : '';
	}

	/**
	 * Flatten a mark to one ink, preserving its alpha.
	 *
	 * The mono assets are rasterised WHITE so this can tint them to anything.
	 * Recolouring a mark baked in the dark ink to white is not possible, which
	 * is why the generator writes them white rather than at their page colour.
	 *
	 * @param \GdImage            $im  Mark.
	 * @param string            $ink Hex colour.
	 *
	 * @return void
	 */
	protected static function tint($im, $ink)
	{
		$hex = ltrim((string) $ink, '#');

		if (strlen($hex) < 6) {
			return;
		}

		$r = (int) hexdec(substr($hex, 0, 2));
		$g = (int) hexdec(substr($hex, 2, 2));
		$b = (int) hexdec(substr($hex, 4, 2));

		$w = imagesx($im);
		$h = imagesy($im);

		for ($y = 0; $y < $h; $y++) {
			for ($x = 0; $x < $w; $x++) {
				$alpha = ( imagecolorat($im, $x, $y) >> 24 ) & 0x7F;

				if ($alpha === 127) {
					continue;
				}

				$tinted = imagecolorallocatealpha($im, $r, $g, $b, $alpha);

				if (false !== $tinted) {
					imagesetpixel($im, $x, $y, $tinted);
				}
			}
		}
	}
