<?php

namespace SmashBalloon\Reviews\Tests\Unit;

use PHPUnit\Framework\TestCase;
use SmashBalloon\Reviews\Common\Builder\SBR_Sources;
use SmashBalloon\Reviews\Common\Services\Upgrade\Routines\RecalculateCollectionRatingsRoutine;

/**
 * SMASH-1685: update_collection_ratings() saved ceil(average), so a collection rated 5,5,3,5,5 showed
 * 5 instead of 4.6 in the feed header, Review Alerts and Trust Badges (all read info.rating).
 * Drives the real method through a $wpdb double: the collection row, its review rows, the saved info.
 */
final class Smash1685CollectionRatingExactTest extends TestCase
{
	/** @var mixed */
	private $previous_wpdb;

	protected function setUp(): void
	{
		parent::setUp();
		$this->previous_wpdb = $GLOBALS['wpdb'] ?? null;
		$GLOBALS['wpdb'] = new class {
			public $prefix = 'wp_';
			/** @var list<array> */
			public $updates = [];
			/** @var array<string, list<array>> review rows per collection id */
			public $reviews = [];
			/** @var list<string> collection ids get_col() returns */
			public $collection_ids = [];
			/** @var string|null provider_id the last prepare() was asked for */
			private $last_arg;

			public function prepare($query, ...$args)
			{
				$this->last_arg = $args[0] ?? null;
				return $query . ' -- ' . wp_json_encode($args);
			}
			public function get_results($query, $output = null)
			{
				if (strpos($query, 'sbr_sources') !== false && strpos($query, 'used_in') !== false) {
					return [ [ 'id' => 1, 'account_id' => $this->last_arg, 'provider' => 'collection', 'name' => 'C', 'info' => '{"rating":0,"total_rating":0}', 'used_in' => 0 ] ];
				}
				if (strpos($query, 'reviews_posts') !== false) {
					return $this->reviews[ $this->last_arg ] ?? [];
				}
				return [];
			}
			public function get_col($query)
			{
				return $this->collection_ids;
			}
			public function update($table, $data, $where, $format = null, $where_format = null)
			{
				$this->updates[] = compact('table', 'data', 'where');
				return 1;
			}
			public function esc_like($text)
			{
				return $text;
			}
		};
	}

	protected function tearDown(): void
	{
		$GLOBALS['wpdb'] = $this->previous_wpdb;
		parent::tearDown();
	}

	private function seed(string $collection_id, array $stars): void
	{
		$GLOBALS['wpdb']->reviews[ $collection_id ] = array_map(function ($s) {
			return [ 'rating' => (string) $s ];
		}, $stars);
	}

	/** @return array{rating: float|int, total_rating: int} the info saved for $collection_id */
	private function saved_info(string $collection_id): array
	{
		foreach (array_reverse($GLOBALS['wpdb']->updates) as $u) {
			if (( $u['where']['account_id'] ?? null ) === $collection_id && isset($u['data']['info'])) {
				return json_decode($u['data']['info'], true);
			}
		}
		$this->fail("no info saved for $collection_id");
	}

	public static function averages(): array
	{
		return [
			'the QA case: one 3 among 5s' => [ [ 5, 5, 3, 5, 5 ], 4.6 ],
			'4 and 5'                      => [ [ 4, 5 ], 4.5 ],
			'two decimals kept'            => [ [ 1, 2, 2 ], 1.67 ],
			'whole number stays whole'     => [ [ 5, 5, 5 ], 5 ],
			'4.1 is not 5'                 => [ [ 4, 4, 4, 4, 4, 4, 4, 4, 4, 5 ], 4.1 ],
		];
	}

	/** @dataProvider averages */
	public function test_collection_rating_is_the_real_average_not_rounded_up(array $stars, $want): void
	{
		$this->seed('collection-1', $stars);
		SBR_Sources::update_collection_ratings('collection-1');
		$info = $this->saved_info('collection-1');
		$this->assertEquals($want, $info['rating'], 'ceil() would give ' . ceil(array_sum($stars) / count($stars)));
		$this->assertSame(count($stars), $info['total_rating']);
	}

	public function test_an_empty_collection_rates_zero(): void
	{
		SBR_Sources::update_collection_ratings('collection-empty');
		$info = $this->saved_info('collection-empty');
		$this->assertSame(0, $info['rating']);
		$this->assertSame(0, $info['total_rating']);
	}

	public function test_routine_recalculates_every_collection(): void
	{
		$GLOBALS['wpdb']->collection_ids = [ 'collection-a', 'collection-b' ];
		$this->seed('collection-a', [ 5, 5, 3, 5, 5 ]);
		$this->seed('collection-b', [ 4, 5 ]);

		( new RecalculateCollectionRatingsRoutine() )->run();

		$this->assertEquals(4.6, $this->saved_info('collection-a')['rating']);
		$this->assertEquals(4.5, $this->saved_info('collection-b')['rating']);
	}

	/** Both stylesheets ship (sbr-functions.php:421 picks one), and the min is regenerated by hand. */
	public static function stylesheets(): array
	{
		return [
			'source'   => [ 'assets/css/sbr-styles.css' ],
			'minified' => [ 'assets/css/sbr-styles.min.css' ],
		];
	}

	/** @dataProvider stylesheets */
	public function test_empty_stars_are_a_fixed_grey_whatever_the_star_colour($file): void
	{
		$css  = (string) file_get_contents(dirname(__DIR__, 2) . '/' . $file);
		$flat = (string) preg_replace('/\s+/', '', $css);
		$this->assertStringContainsString(
			'.sb-item-rating-icon-dimmedsvg{color:#D8DCE6',
			$flat,
			'grayscale() left black/dark stars looking full'
		);
		$this->assertStringNotContainsString('icon-dimmedsvg{filter:grayscale(1)', $flat);
	}

	public function test_routine_does_nothing_without_collections(): void
	{
		( new RecalculateCollectionRatingsRoutine() )->run();
		$this->assertSame([], $GLOBALS['wpdb']->updates);
	}
}
